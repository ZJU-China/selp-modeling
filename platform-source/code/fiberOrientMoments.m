function [A2, A4V] = fiberOrientMoments(alpha, h)
%FIBERORIENTMOMENTS  由 Fisher (von Mises-Fisher) 分布闭式矩构造取向张量。
%
%  参考取向分布 (光交联冻结):
%    rho_f*(x,n) = exp[ alpha_f (h . n) ] / [ 4*pi*sinh(alpha_f)/alpha_f ]
%
%  定义:
%    A_ij^(2)(x)    = int_S2 rho_f* n_i n_j       dOmega   (N x 3 x 3)
%    A_ijkl^ref(x)  = int_S2 rho_f* n_i n_j n_k n_l dOmega  (N x 6 x 6, Voigt)
%
%  实现: 对 u = h.n 的分布矩 <u^2>,<u^4> 用 Langevin 闭式 + 小参数 Taylor 级数
%         (a<=1.5, 20阶, 数值稳定无消去), 再由面内各向同性平均解析构造
%         2 阶与 4 阶矩, 无需球面积分。
%
%  输入:
%    alpha : Nx1 无量纲磁取向参数 alpha_f (>=0)
%    h     : Nx3 磁场单位方向
%  输出:
%    A2   : Nx3x3
%    A4V  : Nx6x6  (Voigt 顺序: 11 22 33 23 13 12)

N = numel(alpha);
h = h ./ max(sqrt(sum(h.^2, 2)), eps);      % 归一化

a = max(alpha(:), 1e-12);

% ---- 矩 <u^2>, <u^4>, u = n.h ----
% 闭式:  b(a) = coth(a) - 1/a (Langevin)
%   <u^2> = 1 - 2b/a
%   <u^4> = 1 - 4b/a + 8/a^2 - 24b/a^3
% 小 a 时两式中 <u^2>,<u^4> 依赖 O(a^{-2}..a^{-3}) 项相互抵消 (灾难性消去),
% 故 a<=1.5 用 20 阶精确 Taylor 级数 (系数由符号积分严格导出)。
m2c = [0.3333333333333333, 0.04444444444444445, -0.004232804232804233, ...
       0.0004232804232804233, -4.275559831115387e-05, 4.328808561612795e-06, ...
       -4.385189570374756e-07, 4.442921757995936e-08, -4.501569303361799e-09, ...
       4.561030240918437e-10, -4.621286519800525e-11, 4.682341363964977e-12, ...
       -4.744203480046731e-13, 4.806883066661541e-14, -4.870390805836674e-15, ...
       4.934737609034415e-16, -4.999934554244162e-17, 5.065992871481270e-18, ...
       -5.132923940565258e-19, 5.200739292027455e-20, -5.269450608830760e-21, ...
       5.339069728314790e-22];
m4c = [0.2, 0.03809523809523810, -0.003386243386243387, ...
       0.0003334936668270002, -3.356549388295420e-05, 3.395389638775882e-06, ...
       -3.438873031154388e-07, 3.483960351957713e-08, -3.529902317621473e-09, ...
       3.576516658076243e-10, -3.623763402843077e-11, 3.671638551873876e-12, ...
       -3.720147280099612e-13, 3.769297166319074e-14, -3.819096480832049e-15, ...
       3.869553752975836e-16, -3.920677662710800e-17, 3.972477014284230e-18, ...
       -4.024960730697569e-19, 4.078137853457997e-20, -4.132017543683773e-21];
m2 = zeros(N,1); m4 = zeros(N,1);
in = a <= 1.5;
if any(in)
    m2(in) = polyval(fliplr(m2c), a(in).^2);
    m4(in) = polyval(fliplr(m4c), a(in).^2);
end
big = ~in;
if any(big)
    L = coth(a(big)) - 1./a(big);
    m2(big) = 1 - 2*L./a(big);
    m4(big) = 1 - 4*L./a(big) + 8./a(big).^2 - 24*L./a(big).^3;
end

% ---- 面内 (垂直 h) 各向同性张量基 ----
hx = h(:,1); hy = h(:,2); hz = h(:,3);

P11 = 1 - hx.^2;  P22 = 1 - hy.^2;  P33 = 1 - hz.^2;
P12 = -hx.*hy;    P13 = -hx.*hz;    P23 = -hy.*hz;

hc{1} = hx; hc{2} = hy; hc{3} = hz;
Pc = cell(3,3);
Pc{1,1}=P11; Pc{2,2}=P22; Pc{3,3}=P33;
Pc{1,2}=P12; Pc{2,1}=P12;
Pc{1,3}=P13; Pc{3,1}=P13;
Pc{2,3}=P23; Pc{3,2}=P23;

% ---- 二阶矩: A2 = <u^2> hh' + (1-<u^2>)/2 * P ----
c1 = (1 - m2)/2;
A2 = zeros(N, 3, 3);
for i = 1:3
    for j = 1:3
        A2(:, i, j) = m2 .* (hc{i}.*hc{j}) + c1 .* Pc{i,j};
    end
end

% ---- 四阶矩 (Voigt 6x6) ----
% A4(i,j,k,l) = m4*h_i h_j h_k h_l
%   + c2*( h_i h_j P_kl + h_i h_k P_jl + h_i h_l P_jk
%       + h_j h_k P_il + h_j h_l P_ik + h_k h_l P_ij )
%   + c3*( P_ij P_kl + P_ik P_jl + P_il P_jk )
% with c2 = (<u^2>-<u^4>)/2 , c3 = (1-2<u^2>+<u^4>)/8
c2 = (m2 - m4)/2;
c3 = (1 - 2*m2 + m4)/8;

pairs = [1 1; 2 2; 3 3; 2 3; 1 3; 1 2];     % Voigt 顺序 11 22 33 23 13 12
A4V = zeros(N, 6, 6);
for A = 1:6
    i = pairs(A,1); j = pairs(A,2);
    for B = 1:6
        k = pairs(B,1); l = pairs(B,2);
        t1 = m4 .* (hc{i}.*hc{j}.*hc{k}.*hc{l});
        t2 = hc{i}.*hc{j}.*Pc{k,l} + hc{i}.*hc{k}.*Pc{j,l} ...
           + hc{i}.*hc{l}.*Pc{j,k} + hc{j}.*hc{k}.*Pc{i,l} ...
           + hc{j}.*hc{l}.*Pc{i,k} + hc{k}.*hc{l}.*Pc{i,j};
        t3 = Pc{i,j}.*Pc{k,l} + Pc{i,k}.*Pc{j,l} + Pc{i,l}.*Pc{j,k};
        A4V(:, A, B) = t1 + c2 .* t2 + c3 .* t3;
    end
end
end