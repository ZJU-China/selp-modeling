#!/usr/bin/env python3
"""
flow_tiger2 -- sequence-driven TIGER2 as a single task.

This merges two steps of the platform chain into one task type.

1. `seq_to_pdb`. As two separate flow steps the pair did not actually work: the
   annotation code (_shared/sequence_annotation.py) looks for
   `<task>/input/sequences.csv` and `<task>/input/*.pdb`, while flow linking
   exposes a predecessor's files at `<task>/input/flow-<prevId>/` -- one
   directory too deep -- and tiger2's `upload_input` deliberately skips
   `flow-*`. So a chained seq_to_pdb -> tiger2 pair uploaded no structure and
   resolved no annotations.

2. `tiger2_dcd_to_gromacs_cg_pdb`, the DCD -> CG conversion. It used to be its
   own flow step between TIGER2 and GROMACS CG, but that step had no main.py, so
   flow start skipped it and it had to be triggered by hand (the Generate
   button). Folding it in means the TIGER2 step produces the CG inputs itself
   from its own trajectory -- `convert()` below imports the same generator the
   standalone transition task uses.

As one task the generated files are written into this task's own input/ where
both the uploader and the viewer look, so the chain actually resolves:

  1. build an extended-chain PDB from config.sequence
  2. write input/sequences.csv from config.annotations  (viewer colouring)
  3. write config/<logPrefix>.conf pointing coordinates at that PDB
  4. delegate the MD command to tiger2/main.py

and, once a trajectory is local (after a sync, or after the viewer downloads
the DCDs), the CG input set (output/cg_start.pdb, output/cg_input.mdp,
output/from-tiger2/, output/README.txt) is regenerated by `convert()`.

Usage mirrors tiger2/main.py:

    flow_tiger2/main.py <command> --task-config CFG --host H --user U ... \
                        --local-dir DIR
    flow_tiger2/main.py synthesize --local-dir DIR [--task-config CFG]
    flow_tiger2/main.py convert    --local-dir DIR [--task-config CFG]

`synthesize` runs steps 1-3 only, so the structure and its annotations can be
generated and inspected without starting a simulation. `convert` runs only the
DCD -> CG conversion, so it can be re-run on its own after new trajectory data
appears.

One thing cannot be automated here: NAMD needs a PSF topology, which is built
by psfgen against force-field parameter files that live on the remote host. Set
`psf` (a filename in input/, or an absolute remote path) to run; otherwise the
structure and annotations are still generated and the command reports exactly
what is missing instead of failing obscurely on the remote host.

TIGER2hs runs are exempt from both the conf generation and the PSF requirement.
A TIGER2hs run reads its own <logPrefix>.conf -- a wrapper sourcing the harness
remd conf that points `tigerimpltop` at an absolute PSF -- and upload_config()
overwrites remote files by name, so generating a NAMD conf here would replace
that wrapper and quietly take the run off the harness. Those tasks synthesise the
structure and the annotation table only, leaving the configuration untouched.
"""

import argparse
import csv
import importlib.util
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TASKTYPE_DIR = os.path.dirname(HERE)
TIGER2_MAIN = os.path.join(TASKTYPE_DIR, "tiger2", "main.py")
SEQ_GEN = os.path.join(TASKTYPE_DIR, "seq_to_pdb", "generate.py")
CG_GEN = os.path.join(TASKTYPE_DIR, "tiger2_dcd_to_gromacs_cg_pdb", "generate.py")

DEFAULT_PARAMETERS = [
    "par_all36_prot.prm",
    "par_all36_cmap.prm",
]


def load_seq_gen():
    """Import seq_to_pdb/generate.py as a module so the chain builder stays in
    exactly one place instead of being forked into this task type."""
    spec = importlib.util.spec_from_file_location("seq_to_pdb_generate", SEQ_GEN)
    if spec is None or spec.loader is None:
        raise RuntimeError("cannot import seq_to_pdb generator at %s" % SEQ_GEN)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def load_cg_gen():
    """Import the DCD -> CG generator this task type folds in.

    Same reasoning as load_seq_gen: the standalone
    `tiger2_dcd_to_gromacs_cg_pdb` task and this wrapper must convert
    identically, so the conversion is imported rather than copied."""
    spec = importlib.util.spec_from_file_location("tiger2_dcd_to_cg_generate", CG_GEN)
    if spec is None or spec.loader is None:
        raise RuntimeError("cannot import DCD -> CG generator at %s" % CG_GEN)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def read_config(path):
    if not path:
        return {}
    try:
        with open(path) as f:
            return json.load(f) or {}
    except Exception:
        return {}


def annotation_rows(config, input_dir):
    """Prefer a CSV the Parameters form wrote, else config.annotations -- the
    same precedence seq_to_pdb uses, so both entry points behave alike."""
    csv_path = os.path.join(input_dir, "annotations.csv")
    if os.path.exists(csv_path):
        with open(csv_path, newline="") as f:
            return list(csv.DictReader(f))
    return list(config.get("annotations") or [])


def normalise_sequence(seq):
    return "".join(str(seq or "").split()).upper()


def safe_name(text, fallback="protein"):
    out = (str(text or "").strip().replace(" ", "_")) or fallback
    return "".join(c for c in out if c.isalnum() or c in "_-.")


def build_conf(path, *, psf, pdb_name, protein, num_replicas, steps_per_cycle,
               total_cycles, temperature, temp_low, temp_high, parameters):
    total_steps = int(steps_per_cycle) * int(total_cycles)
    lines = [
        "# Generated by the flow_tiger2 task from sequence input.",
        "#   protein  : %s" % protein,
        "#   coordinates: %s" % pdb_name,
        "structure    %s" % psf,
        "coordinates  %s" % pdb_name,
    ]
    for p in parameters:
        lines.append("parameters   %s" % p)
    lines += [
        "temperature  %.1f" % temperature,
        "timestep     2.0",
        "switching    on",
        "switchdist   10.0",
        "cutoff       12.0",
        "pairlistdist 14.0",
        "exclude      scaled1-4",
        "1-4scaling   1.0",
        "",
        "gbis         on",
        "soluteDielectric 1.0",
        "solventDielectric 80.0",
        "alphaCutoff  12.0",
        "",
        "langevin          on",
        "langevinTemp      %.1f" % temperature,
        "langevinDamping   1.0",
        "langevinHydrogen  off",
        "",
        "replicas           %d" % int(num_replicas),
        "replicaBasisTemp   %.1f" % temperature,
        "replicaTempLow     %.1f" % temp_low,
        "replicaTempHigh    %.1f" % temp_high,
        "replicaUseTemps    on",
        "replicaBasisScale  1.0",
        "",
        "run %d" % total_steps,
        "",
    ]
    with open(path, "w") as f:
        f.write("\n".join(lines))
    return total_steps


def synthesize(local_dir, config):
    """Steps 1-3. Returns a result dict; never raises for user-fixable input,
    so the caller can report a precise message."""
    seq_mod = load_seq_gen()

    input_dir = os.path.join(local_dir, "input")
    config_dir = os.path.join(local_dir, "config")
    for d in (input_dir, config_dir):
        os.makedirs(d, exist_ok=True)

    defaults = config.get("defaults") or {}
    protein = str(config.get("protein") or defaults.get("protein") or "protein").strip()
    sequence = normalise_sequence(config.get("sequence"))
    rows = annotation_rows(config, input_dir)

    if not sequence:
        return {
            "ok": False,
            "error": "No sequence set. Fill in the Sequence field on the Parameters "
                     "panel and save before starting.",
            "stage": "sequence",
        }

    try:
        residues = seq_mod.build_extended_chain(sequence)
    except KeyError as e:
        return {"ok": False, "error": "Unknown amino-acid letter in sequence: %s" % e, "stage": "sequence"}
    except ValueError as e:
        return {"ok": False, "error": str(e), "stage": "sequence"}

    pdb_name = "%s_extended.pdb" % safe_name(protein)
    pdb_path = os.path.join(input_dir, pdb_name)
    natoms = seq_mod.write_pdb(residues, pdb_path)

    # sequences.csv is what /api/data/sequence-annotations reads to colour the
    # DCD, so it goes next to the structure in this task's own input dir.
    seq_mod.write_sequences_csv(rows, os.path.join(input_dir, "sequences.csv"))

    psf = str(config.get("psf") or "").strip()
    psf_ready = bool(psf) and (
        os.path.isabs(psf) or os.path.exists(os.path.join(input_dir, psf))
    )

    # How the run is actually configured decides whether this task owns a NAMD
    # config file at all.
    #
    # A plain run reads <logPrefix>.conf straight, so we generate it. A TIGER2hs
    # run does not: its <logPrefix>.conf is a thin wrapper that sources the
    # harness's remd conf, which points `tigerimpltop` at an absolute PSF.
    # upload_config() pushes local config/*.conf to remote temp/ *overwriting by
    # name*, so writing ours would replace that wrapper and the next run would
    # stop going through the harness entirely. So for TIGER2hs we synthesise the
    # structure and annotations only, and leave the configuration alone.
    harness = "tiger2hs" if (defaults.get("tiger2hs") or config.get("tiger2hs")) else "namd"

    if harness == "tiger2hs":
        return {
            "ok": True,
            "harness": harness,
            "protein": protein,
            "sequence": sequence,
            "residues": len(residues),
            "atoms": natoms,
            "annotations": len(rows),
            "pdb": os.path.join("input", pdb_name),
            "sequencesCsv": os.path.join("input", "sequences.csv"),
            "conf": None,
            "confNote": "TIGER2hs supplies its own config (tigerimpltop); no NAMD "
                        "conf was generated, so the harness configuration is untouched.",
            "psfReady": True,
            "psf": psf or None,
        }

    log_prefix = str(config.get("logPrefix") or "").strip() or safe_name(protein, "tiger2")
    params = config.get("parameters") or DEFAULT_PARAMETERS

    conf_rel = os.path.join("config", "%s.conf" % log_prefix)
    total_steps = build_conf(
        os.path.join(local_dir, conf_rel),
        psf=psf or "FILL-IN:supply-a-psf-built-by-psfgen",
        pdb_name=pdb_name,
        protein=protein,
        num_replicas=config.get("numReplicas") or defaults.get("numReplicas") or 4,
        steps_per_cycle=config.get("stepsPerCycle") or defaults.get("stepsPerCycle") or 15000,
        total_cycles=config.get("totalCycles") or defaults.get("totalCycles") or 1,
        temperature=float(config.get("temperature") or defaults.get("temperature") or 310.0),
        temp_low=float(config.get("tempLow") or 300.0),
        temp_high=float(config.get("tempHigh") or 400.0),
        parameters=params,
    )

    return {
        "ok": True,
        "harness": harness,
        "protein": protein,
        "sequence": sequence,
        "residues": len(residues),
        "atoms": natoms,
        "annotations": len(rows),
        "pdb": os.path.join("input", pdb_name),
        "sequencesCsv": os.path.join("input", "sequences.csv"),
        "conf": conf_rel,
        "totalSteps": total_steps,
        "psfReady": psf_ready,
        "psf": psf or None,
    }


def convert(local_dir, config):
    """Produce the CG input set from this task's own trajectory.

    This is the DCD -> CG conversion the former `tiger2_dcd_to_gromacs_cg_pdb`
    flow step performed, folded into the TIGER2 step. The source is this task's
    own output/ (the DCDs arrive there via sync), and its cache/trajectory/
    (the DCDs the viewer downloads); both are searched by the generator.

    Never raises for user-fixable input: the generator returns notes instead,
    which the caller surfaces verbatim.
    """
    gen = load_cg_gen()
    output_dir = os.path.join(local_dir, "output")

    # Mirror synthesize()'s resolution so the CG start temperature matches the
    # MD run it came from: config.temperature, then config.defaults.temperature,
    # then 310 K -- converted to Celsius, which is what the generator takes.
    # temperatureC is honoured first only so the standalone transition task's
    # field (if it is ever set here) still wins.
    if config.get("temperatureC") is not None:
        temperature_c = config.get("temperatureC")
    else:
        defaults = config.get("defaults") or {}
        kelvin = config.get("temperature") or defaults.get("temperature") or 310.0
        temperature_c = float(kelvin) - 273.15

    return gen.convert(
        output_dir,
        output_dir,
        temperature_c=temperature_c,
        src_id="",
        snapshot=True,
        generator="flow_tiger2 task (folded DCD → CG conversion)",
    )


def build_arg_parser():
    # Mirror tiger2's CLI so buildMainArgs can pass it through unchanged.
    p = argparse.ArgumentParser(description="flow_tiger2: sequence-driven TIGER2")
    p.add_argument("command", choices=[
        "synthesize",
        # The DCD -> CG conversion folded in from the (now removed) flow step.
        "convert",
        # pause/continue are handled by tiger2/main.py, which this wrapper
        # delegates to verbatim; listed here so argparse does not reject them.
        "start", "stop", "restart", "status", "pause", "continue",
        "sync", "converge",
        "convergence-check", "organize", "progress", "monitor", "checkpoint",
        "structure", "cluster", "trajectory-info", "gen-trajectory", "log-paths",
        "route",
    ])
    p.add_argument("--task-config", default=None)
    p.add_argument("--host", default=None)
    p.add_argument("--port", type=int, default=22)
    p.add_argument("--user", default=None)
    p.add_argument("--key", default=None)
    p.add_argument("--password", default=None)
    p.add_argument("--remote-dir", default=None)
    p.add_argument("--local-dir", required=True)
    p.add_argument("--log-prefix", default=None)
    p.add_argument("--namd-bin", default=None)
    p.add_argument("--cores", type=int, default=None)
    p.add_argument("--num-replicas", type=int, default=None)
    p.add_argument("--steps-per-cycle", type=int, default=None)
    p.add_argument("--total-cycles", type=int, default=None)
    p.add_argument("--output", default=None)
    p.add_argument("--replica", type=int, default=0)
    p.add_argument("--gen-pdb-script", default=None)
    p.add_argument("--stop-cmd", default=None)
    p.add_argument("--route", default=None)
    p.add_argument("--sub", default=None)
    p.add_argument("--path", default=None)
    p.add_argument("--content", default=None)
    p.add_argument("--cmd", default=None)
    p.add_argument("--timeout", type=int, default=None)
    return p


def _best_effort_convert(local_dir, config):
    """Run the conversion, never letting its failure abort the caller.

    A start must not fail because there is no trajectory yet (the first run
    produces one later), so any error is folded into the returned dict.
    """
    try:
        return convert(local_dir, config)
    except Exception as e:
        return {"ok": False, "error": str(e)}


def _delegate_capture():
    """Delegate to tiger2/main.py, capturing its stdout.

    Needed by commands after which trajectory data may have just become local
    (sync/organize/trajectory download), so the CG inputs can be regenerated
    and merged into the delegate's JSON response. runMain parses stdout as a
    single JSON object, so the delegate's output is captured and re-emitted
    merged rather than streamed and followed by a second object.
    """
    proc = subprocess.run(
        [sys.executable, TIGER2_MAIN] + sys.argv[1:],
        capture_output=True, text=True,
    )
    if proc.stderr:
        sys.stderr.write(proc.stderr)
    raw = (proc.stdout or "").strip()
    try:
        payload = json.loads(raw)
    except Exception:
        payload = None
    return proc.returncode, raw, payload


# Commands after which the local trajectory may have just appeared, so the CG
# inputs should be regenerated from it: sync/organize pull the run output down,
# and the viewer's trajectory route downloads the DCDs it plots.
def _brings_trajectory_local(args):
    if args.command in ("sync", "organize"):
        return True
    return args.command == "route" and args.route == "trajectory"


def main():
    args = build_arg_parser().parse_args()
    config = read_config(args.task_config)

    if args.command == "synthesize":
        result = synthesize(args.local_dir, config)
        print(json.dumps(result))
        return 0 if result.get("ok") else 1

    if args.command == "convert":
        result = _best_effort_convert(args.local_dir, config)
        print(json.dumps(result))
        return 0 if result.get("ok") else 1

    # Build the structure from the current parameters before every start, so
    # editing the sequence on the Parameters panel and restarting re-generates
    # the structure instead of silently reusing the previous one.
    if args.command in ("start", "restart"):
        result = synthesize(args.local_dir, config)
        if not result.get("ok"):
            print(json.dumps(result))
            return 1
        # Refresh the CG inputs from any trajectory already on disk, so a start
        # after a completed, synced run hands fresh files to the CG step. This
        # mirrors flow_gromacs_cg regenerating its inputs on every start.
        # Best-effort and reported on stderr so the delegate's stdout JSON --
        # which flow start parses -- stays a single object.
        conv = _best_effort_convert(args.local_dir, config)
        print(json.dumps({"ok": True, "convert": conv}), file=sys.stderr)
        if not result.get("psfReady"):
            # The structure and its annotations are on disk and viewable, but
            # NAMD cannot run without a PSF topology. Say so precisely.
            print(json.dumps({
                "ok": False,
                "stage": "psf",
                "error": "Generated %s and input/sequences.csv, but no PSF topology is set. "
                         "NAMD needs a PSF built by psfgen on the remote host: place it in this "
                         "task's input/ and set the PSF field on the Parameters panel."
                         % result.get("pdb"),
                "synthesized": result,
            }))
            return 1
        print(json.dumps({"ok": True, "synthesized": result}), file=sys.stderr)

    # Commands after which the local trajectory may have just appeared (a sync,
    # an organize, or the viewer downloading the DCDs): regenerate the CG inputs
    # and merge the result into the delegate's response.
    if _brings_trajectory_local(args):
        rc, raw, payload = _delegate_capture()
        conv = _best_effort_convert(args.local_dir, config)
        if isinstance(payload, dict):
            payload["convert"] = conv
            print(json.dumps(payload))
        else:
            # The delegate's output was not a JSON object; keep it verbatim
            # rather than dropping it, and report the conversion separately.
            if raw:
                print(raw)
            print(json.dumps({"ok": True, "convert": conv}), file=sys.stderr)
        return rc

    # Delegate the MD command to tiger2 verbatim, preserving argv (SSH
    # credentials, routing flags, replica selectors).
    return subprocess.call([sys.executable, TIGER2_MAIN] + sys.argv[1:])


if __name__ == "__main__":
    sys.exit(main())
